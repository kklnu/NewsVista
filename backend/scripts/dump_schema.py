"""Write migrations/001_init.sql (PostgreSQL DDL) from the SQLAlchemy models.

    python -m scripts.dump_schema
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from sqlalchemy.dialects import postgresql  # noqa: E402
from sqlalchemy.schema import CreateIndex, CreateTable  # noqa: E402

from app.models import Base  # noqa: E402

out = ["-- NewsVista schema (PostgreSQL / Supabase). Generated by scripts/dump_schema.py.",
       "-- The API also runs metadata.create_all() at startup, which is idempotent.", ""]
for table in Base.metadata.sorted_tables:
    ddl = str(CreateTable(table, if_not_exists=True).compile(dialect=postgresql.dialect())).strip()
    out.append(ddl + ";\n")
    for index in table.indexes:
        out.append(str(CreateIndex(index, if_not_exists=True).compile(dialect=postgresql.dialect())).strip() + ";")
    out.append("")
path = Path(__file__).resolve().parent.parent / "migrations" / "001_init.sql"
path.write_text("\n".join(out), encoding="utf-8")
print(f"wrote {path}")
